    fun findDtc(code: String): DtcInfo? {
        val cleanCode = code.trim().uppercase().replace("^[^A-Z0-9]+".toRegex(), "")
        val directMatch = dtcMap[cleanCode] ?: dtcMap.entries.firstOrNull { cleanCode.contains(it.key) }?.value
        if (directMatch != null) return directMatch
        
        // If code matches standard OBD2 pattern e.g. P061D, P1234, C0035, U0100
        val obdRegex = "([P|C|B|U][0-9A-F]{4})".toRegex(RegexOption.IGNORE_CASE)
        val match = obdRegex.find(cleanCode)?.value?.uppercase()
        if (match != null) {
            val prefix = match.substring(0, 3)
            val category = when (match.first()) {
                'P' -> when (prefix) {
                    "P00", "P01", "P02" -> "Топливная система и воздухоподача (Powertrain)"
                    "P03" -> "Система зажигания и пропуски сгорания"
                    "P04" -> "Система снижения токсичности выхлопа"
                    "P05" -> "Контроль холостого хода и скорости"
                    "P06" -> "Модуль управления ДВС / ЭБУ (ECM/PCM)"
                    "P07", "P08", "P09" -> "Управление трансмиссией и АКПП"
                    else -> "Система силового агрегата ДВС (Powertrain)"
                }
                'C' -> "Ходовая часть и тормозная система (Chassis ABS/ESP)"
                'B' -> "Кузовная электроника и комфорт (Body Control)"
                'U' -> "Шина передачи данных и сетевые блоки (Network CAN-Bus)"
                else -> "Диагностический код OBD2"
            }
            return DtcInfo(
                code = match,
                title = "Код ошибки $match ($category)",
                category = category,
                severity = "ПРЕДУПРЕЖДЕНИЕ",
                causes = listOf("Неисправность соответствующего датчика или исполнительного механизма", "Повреждение проводки, окисление разъема или потеря заземления", "Сбой параметров в памяти электронного блока управления"),
                symptoms = listOf("Горит индикатор Check Engine / Warning", "Возможно снижение эффективности работы системы", "Сохранен фрейм данных Freeze Frame в ECU"),
                solution = "1. Осмотрите проводку и разъем компонента.\n2. Проверьте параметры сигнала сканером в режиме Live Data.\n3. Выполните сброс ошибки через меню 'Очистить ошибки'."
            )
        }
        return null
    }

    fun searchDatabase(query: String): List<DtcInfo> {
        val q = query.lowercase()
        return dtcMap.values.filter {
            it.code.lowercase().contains(q) ||
            it.title.lowercase().contains(q) ||
            it.category.lowercase().contains(q) ||
            it.solution.lowercase().contains(q)
        }
    }
